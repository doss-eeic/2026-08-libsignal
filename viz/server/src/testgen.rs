use std::collections::BTreeMap;
use std::time::{SystemTime, UNIX_EPOCH};

use anyhow::{Result, anyhow};

use crate::sim::{Action, ActionType, Expect, Who};

/// Renders a self-contained protocol integration test from the actions recorded by the UI.
pub(crate) fn generate(name: &str, actions: &[Action]) -> Result<String> {
    if !valid_name(name) {
        return Err(anyhow!("テスト名が正しくありません"));
    }

    let messages = messages(actions)?;
    let has_tamper = actions
        .iter()
        .any(|action| action.action_type == ActionType::Tamper);
    let mut source = String::new();
    source.push_str(&format!("// generated by the viz tool at {}\n", iso_now()));
    for action in actions {
        source.push_str("// ");
        source.push_str(&describe(action));
        source.push('\n');
    }
    source.push_str(
        "\
mod support;

use futures_util::FutureExt;
use libsignal_protocol::*;
use rand::rngs::OsRng;
use rand::TryRngCore as _;
use std::time::SystemTime;
use support::*;

type TestResult<T = ()> = Result<T, SignalProtocolError>;

fn reparse(message: &CiphertextMessage) -> TestResult<CiphertextMessage> {
    match message.message_type() {
        CiphertextMessageType::PreKey => Ok(CiphertextMessage::PreKeySignalMessage(
            PreKeySignalMessage::try_from(message.serialize())?,
        )),
        CiphertextMessageType::Whisper => Ok(CiphertextMessage::SignalMessage(
            SignalMessage::try_from(message.serialize())?,
        )),
        _ => unreachable!(\"viz only creates pre-key and whisper messages\"),
    }
}
",
    );
    if has_tamper {
        source.push_str(
            "\
fn tampered(message: &CiphertextMessage) -> TestResult<CiphertextMessage> {
    let mut bytes = message.serialize().to_vec();
    let signal_range = match message.message_type() {
        CiphertextMessageType::PreKey => field_bytes(&bytes, 1, 4).expect(\"embedded SignalMessage\"),
        CiphertextMessageType::Whisper => (0, bytes.len()),
        _ => unreachable!(\"viz only creates pre-key and whisper messages\"),
    };
    // SignalMessage ends in an eight-byte MAC. Field 4 is its encrypted payload.
    let (start, end) = field_bytes(&bytes[signal_range.0..signal_range.1], 1, 4)
        .expect(\"SignalMessage ciphertext\");
    let index = signal_range.0 + start + (end - start) / 2;
    bytes[index] ^= 1;
    match message.message_type() {
        CiphertextMessageType::PreKey => Ok(CiphertextMessage::PreKeySignalMessage(
            PreKeySignalMessage::try_from(bytes.as_slice())?,
        )),
        CiphertextMessageType::Whisper => Ok(CiphertextMessage::SignalMessage(
            SignalMessage::try_from(bytes.as_slice())?,
        )),
        _ => unreachable!(\"viz only creates pre-key and whisper messages\"),
    }
}

fn field_bytes(bytes: &[u8], offset: usize, wanted: u32) -> Option<(usize, usize)> {
    let mut cursor = offset;
    while cursor < bytes.len() {
        let tag = read_varint(bytes, &mut cursor)?;
        let field = (tag >> 3) as u32;
        match (tag & 7, field == wanted) {
            (2, true) => {
                let length = read_varint(bytes, &mut cursor)? as usize;
                let end = cursor.checked_add(length)?;
                return (end <= bytes.len()).then_some((cursor, end));
            }
            (0, _) => { read_varint(bytes, &mut cursor)?; }
            (1, _) => cursor = cursor.checked_add(8)?,
            (2, _) => {
                let length = read_varint(bytes, &mut cursor)? as usize;
                cursor = cursor.checked_add(length)?;
            }
            (5, _) => cursor = cursor.checked_add(4)?,
            _ => return None,
        }
        if cursor > bytes.len() { return None; }
    }
    None
}

fn read_varint(bytes: &[u8], cursor: &mut usize) -> Option<u64> {
    let mut value = 0_u64;
    for shift in (0..64).step_by(7) {
        let byte = *bytes.get(*cursor)?;
        *cursor += 1;
        value |= u64::from(byte & 0x7f) << shift;
        if byte & 0x80 == 0 { return Some(value); }
    }
    None
}
",
        );
    }
    source.push_str(&format!(
        "\
#[test]
fn viz_{name}() -> TestResult {{
    async {{
        let mut csprng = OsRng.unwrap_err();
        let alice_addr = ProtocolAddress::new(\"alice\".to_owned(), DeviceId::new(1).unwrap());
        let bob_addr = ProtocolAddress::new(\"bob\".to_owned(), DeviceId::new(1).unwrap());
        let mut alice_store_builder = TestStoreBuilder::new();
        let mut bob_store_builder = TestStoreBuilder::new();
        bob_store_builder.add_pre_key(IdChoice::Next);
        bob_store_builder.add_signed_pre_key(IdChoice::Next);
        bob_store_builder.add_kyber_pre_key(IdChoice::Next);
        let bob_bundle = bob_store_builder.make_bundle_with_latest_keys(DeviceId::new(1).unwrap());
        process_prekey_bundle(
            &bob_addr,
            &alice_addr,
            &mut alice_store_builder.store.session_store,
            &mut alice_store_builder.store.identity_store,
            &bob_bundle,
            SystemTime::now(),
            &mut csprng,
        )
        .await?;
"
    ));

    for action in actions {
        match action.action_type {
            ActionType::Send => {
                let message = messages.get(&action.message_id).expect("validated action");
                source.push_str(&format!(
                    "        let m{} = encrypt(&mut {}_store_builder.store, &{}_addr, &{}_addr, {}).await?;\n",
                    action.message_id,
                    who_name(message.from),
                    who_name(message.to),
                    who_name(message.from),
                    rust_string(&message.text),
                ));
                if action.delivered_now == Some(true) {
                    emit_delivery(&mut source, action, message, false)?;
                }
            }
            ActionType::Deliver => {
                let message = messages.get(&action.message_id).expect("validated action");
                emit_delivery(&mut source, action, message, false)?;
            }
            ActionType::Replay => {
                let message = messages.get(&action.message_id).expect("validated action");
                emit_delivery(&mut source, action, message, false)?;
            }
            ActionType::Tamper => {
                let message = messages.get(&action.message_id).expect("validated action");
                emit_delivery(&mut source, action, message, true)?;
            }
        }
    }
    source.push_str(
        "\
        Ok(())
    }
    .now_or_never()
    .expect(\"sync\")
}
",
    );
    Ok(source)
}

#[derive(Clone)]
struct MessageInfo {
    from: Who,
    to: Who,
    text: String,
}

fn messages(actions: &[Action]) -> Result<BTreeMap<u32, MessageInfo>> {
    let mut result = BTreeMap::new();
    for action in actions
        .iter()
        .filter(|action| action.action_type == ActionType::Send)
    {
        let text = action
            .text
            .clone()
            .ok_or_else(|| anyhow!("送信操作に本文がありません"))?;
        result.insert(
            action.message_id,
            MessageInfo {
                from: action.who,
                to: other(action.who),
                text,
            },
        );
    }
    for action in actions {
        if !result.contains_key(&action.message_id) {
            return Err(anyhow!(
                "メッセージ #{} の送信がありません",
                action.message_id
            ));
        }
    }
    Ok(result)
}

fn emit_delivery(
    source: &mut String,
    action: &Action,
    message: &MessageInfo,
    tamper: bool,
) -> Result<()> {
    let expression = if tamper {
        format!("tampered(&m{})?", action.message_id)
    } else {
        format!("reparse(&m{})?", action.message_id)
    };
    source.push_str(&format!(
        "        let received_{} = {};\n        let result_{} = decrypt(&mut {}_store_builder.store, &{}_addr, &{}_addr, &received_{}).await;\n",
        action.i,
        expression,
        action.i,
        who_name(message.to),
        who_name(message.from),
        who_name(message.to),
        action.i,
    ));
    match action.expect {
        Expect::Ok => source.push_str(&format!(
            "        let plaintext_{} = result_{}?;\n        assert_eq!(String::from_utf8(plaintext_{}).expect(\"utf8\"), {});\n",
            action.i,
            action.i,
            action.i,
            rust_string(&message.text),
        )),
        Expect::Duplicate => source.push_str(&format!(
            "        assert!(matches!(result_{}, Err(SignalProtocolError::DuplicatedMessage(..))));\n",
            action.i
        )),
        Expect::BadMac => source.push_str(&format!(
            "        assert!(matches!(result_{}, Err(SignalProtocolError::InvalidMessage(..))));\n",
            action.i
        )),
        Expect::Error | Expect::AnyError => source.push_str(&format!(
            "        assert!(result_{}.is_err());\n",
            action.i
        )),
    }
    Ok(())
}

fn valid_name(name: &str) -> bool {
    let bytes = name.as_bytes();
    !bytes.is_empty()
        && bytes.len() <= 40
        && bytes[0].is_ascii_lowercase()
        && bytes
            .iter()
            .all(|byte| byte.is_ascii_lowercase() || byte.is_ascii_digit() || *byte == b'_')
}

fn who_name(who: Who) -> &'static str {
    match who {
        Who::Alice => "alice",
        Who::Bob => "bob",
    }
}

fn other(who: Who) -> Who {
    match who {
        Who::Alice => Who::Bob,
        Who::Bob => Who::Alice,
    }
}

fn rust_string(value: &str) -> String {
    format!("{value:?}")
}

fn iso_now() -> String {
    let seconds = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .expect("system clock after Unix epoch")
        .as_secs() as i64;
    let days = seconds.div_euclid(86_400);
    let clock = seconds.rem_euclid(86_400);
    let (year, month, day) = civil_from_days(days);
    format!(
        "{year:04}-{month:02}-{day:02}T{:02}:{:02}:{:02}Z",
        clock / 3_600,
        (clock % 3_600) / 60,
        clock % 60
    )
}

// Gregorian calendar conversion, with day zero at 1970-01-01.
fn civil_from_days(days: i64) -> (i64, i64, i64) {
    let z = days + 719_468;
    let era = if z >= 0 { z } else { z - 146_096 } / 146_097;
    let doe = z - era * 146_097;
    let yoe = (doe - doe / 1_460 + doe / 36_524 - doe / 146_096) / 365;
    let year = yoe + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let day = doy - (153 * mp + 2) / 5 + 1;
    let month = mp + if mp < 10 { 3 } else { -9 };
    (year + i64::from(month <= 2), month, day)
}

fn describe(action: &Action) -> String {
    let person = match action.who {
        Who::Alice => "Alice",
        Who::Bob => "Bob",
    };
    match action.action_type {
        ActionType::Send if action.delivered_now == Some(true) => {
            format!(
                "{}. {person} が #{} を送信してすぐ届ける",
                action.i + 1,
                action.message_id
            )
        }
        ActionType::Send => format!(
            "{}. {person} が #{} を送信",
            action.i + 1,
            action.message_id
        ),
        ActionType::Deliver => format!(
            "{}. {person} が #{} を受信",
            action.i + 1,
            action.message_id
        ),
        ActionType::Tamper => format!(
            "{}. Mallory が #{} を改ざん",
            action.i + 1,
            action.message_id
        ),
        ActionType::Replay => format!("{}. Mallory が #{} を再送", action.i + 1, action.message_id),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::sim::Sim;
    use std::path::PathBuf;

    #[test]
    fn escapes_unicode_and_all_expectations() -> Result<()> {
        let mut sim = Sim::new()?;
        sim.send(Who::Alice, "あ\"\\\n".into(), false)?;
        sim.deliver(1)?;
        sim.script[1].expect = Expect::AnyError;
        let generated = generate("escaped", &sim.script)?;
        assert!(generated.contains("\"あ\\\"\\\\\\n\""));
        assert!(generated.contains("result_1.is_err()"));
        Ok(())
    }

    #[test]
    #[ignore = "runs Cargo against a generated protocol integration test"]
    fn generated_script_runs() -> Result<()> {
        let name = "viz_testgen_e2e";
        let path = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
            .join("../../rust/protocol/tests")
            .join(format!("{name}.rs"));
        if path.exists() {
            return Err(anyhow!("refusing to overwrite {}", path.display()));
        }
        let mut sim = Sim::new()?;
        sim.send(Who::Alice, "今\"\\\n".into(), true)?;
        sim.send(Who::Bob, "reply".into(), true)?;
        sim.send(Who::Alice, "first".into(), false)?;
        sim.send(Who::Alice, "second".into(), false)?;
        sim.deliver(4)?;
        sim.deliver(3)?;
        sim.send(Who::Bob, "tamper".into(), false)?;
        sim.tamper(5)?;
        sim.deliver(5)?;
        sim.replay(5)?;
        let generated = generate("testgen_e2e", &sim.script)?;
        std::fs::write(&path, generated)?;
        let runtime = tokio::runtime::Runtime::new()?;
        let result = runtime.block_on(async {
            crate::runner::format_generated(&path).await?;
            crate::runner::run("testgen_e2e").await
        });
        std::fs::remove_file(&path)?;
        assert!(result?.passed);
        Ok(())
    }
}
